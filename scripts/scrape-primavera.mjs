#!/usr/bin/env node
// Scrapes the Primavera Sound Barcelona lineup from the GraphQL API that backs
// https://www.primaverasound.com/es/barcelona/lineup and writes it as a seed
// module for the app's SQLite database.
//
//   node scripts/scrape-primavera.mjs [event] [output]
//
// Defaults: event "primavera-sound-2027-barcelona",
//           output "src/db/seeds/primavera2027.ts".
//
// Set times are emitted as Europe/Madrid wall-clock ISO strings (the format the
// app stores) once the festival publishes them; until then the API reports
// "tbd" and the seed carries null times. The lineup API does not expose stage
// names, so stage stays null.
//
// Seed modules are inserted by a database migration exactly once. If the
// lineup changes after a release, add a new migration that updates rows by
// artist instead of editing an already-shipped seed.

import { writeFileSync } from 'node:fs';

const EVENT = process.argv[2] ?? 'primavera-sound-2027-barcelona';
const OUTPUT = process.argv[3] ?? 'src/db/seeds/primavera2027.ts';
const ENDPOINT = 'https://graphql.primaverasound.com/prod/graphql';
const TIMEZONE = 'Europe/Madrid';

const QUERY = `query Get($name: String!) {
  getLineupEvent(name: $name) {
    artists {
      artistName
      venues { duration dateTimeStartReal }
    }
  }
}`;

function wallClock(epochMs) {
  const parts = Object.fromEntries(
    new Intl.DateTimeFormat('en-CA', {
      timeZone: TIMEZONE,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hourCycle: 'h23',
    })
      .formatToParts(new Date(epochMs))
      .map((p) => [p.type, p.value])
  );
  return `${parts.year}-${parts.month}-${parts.day}T${parts.hour}:${parts.minute}:${parts.second}`;
}

const url = new URL(ENDPOINT);
url.searchParams.set('query', QUERY);
url.searchParams.set('operationName', 'Get');
url.searchParams.set('variables', JSON.stringify({ name: EVENT }));

const res = await fetch(url, { headers: { origin: 'https://www.primaverasound.com' } });
if (!res.ok) throw new Error(`HTTP ${res.status} from ${ENDPOINT}`);
const body = await res.json();
const artists = body?.data?.getLineupEvent?.artists;
if (!Array.isArray(artists) || artists.length === 0) {
  throw new Error(`No artists returned for ${EVENT}: ${JSON.stringify(body).slice(0, 300)}`);
}

const shows = artists.flatMap((a) =>
  a.venues.map((v) => {
    const startMs = Number(v.dateTimeStartReal);
    const timed = v.dateTimeStartReal !== 'tbd' && Number.isFinite(startMs);
    return {
      artist: a.artistName.trim(),
      startTime: timed ? wallClock(startMs) : null,
      endTime: timed ? wallClock(startMs + v.duration * 60_000) : null,
    };
  })
);
shows.sort((a, b) => a.artist.localeCompare(b.artist, 'en', { sensitivity: 'base' }));

const rows = shows
  .map((s) => `  { artist: ${JSON.stringify(s.artist)}, startTime: ${JSON.stringify(s.startTime)}, endTime: ${JSON.stringify(s.endTime)} },`)
  .join('\n');

writeFileSync(
  OUTPUT,
  `// Generated by scripts/scrape-primavera.mjs from the official lineup API
// (event "${EVENT}") on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
import type { SeedShow } from '../../types';

const SHOWS: SeedShow[] = [
${rows}
];

export default SHOWS;
`
);
console.log(`Wrote ${shows.length} shows (${shows.filter((s) => s.startTime).length} with set times) to ${OUTPUT}`);
